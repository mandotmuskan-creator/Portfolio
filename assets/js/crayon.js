/* =========================================================
   crayon.js — the illustration system.

   Every drawing in this site is an independent asset. Nothing
   is baked into a background image, so each piece can be
   placed, rotated and sized on its own.

   Markup form
   -----------
     <span data-crayon="flower" data-size="sm" data-rot="-8"></span>
     <span data-face="happy"    data-size="lg"></span>
     <span data-doodle="arrow-red" data-rot="12"></span>

   String form, for the JS-rendered pages
   --------------------------------------
     crayon({ name:'flower', size:'sm', rot:-8 })
     face('happy', { size:'lg', alt:'Muskan, laughing' })
     doodle('arrow-red', { rot: 12 })

   Assets carry aria-hidden unless an `alt` is supplied, so a
   screen reader walks straight past the decoration.
   ========================================================= */

(function (global) {
  'use strict';

  var DIRS = { crayon: 'assets/img/crayon/', face: 'assets/img/face/', doodle: 'assets/img/doodle/' };
  var SIZES = { xs: 1, sm: 1, md: 1, lg: 1, xl: 1 };

  /* Natural aspect ratios, so the browser reserves the right box before the
     file lands and nothing shifts on load. Generated by scripts/build_assets.py
     and pasted in — see assets/img/crayon-manifest.json for the source. */
  var RATIO = global.CRAYON_RATIO || {};

  function esc(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }

  /**
   * Build the markup for one asset.
   * @param {object} o
   * @param {string} o.kind   crayon | face | doodle
   * @param {string} o.name   file name without extension
   * @param {string} [o.size] xs | sm | md | lg | xl
   * @param {number} [o.rot]  degrees
   * @param {string} [o.alt]  real alt text; omit to mark it decorative
   * @param {string} [o.cls]  extra classes
   * @param {boolean} [o.eager] skip lazy-loading (above the fold)
   */
  function asset(o) {
    var kind = o.kind || 'crayon';
    var size = SIZES[o.size] ? o.size : 'md';
    var rot = Number(o.rot) || 0;
    var r = RATIO[kind + '/' + o.name];

    var cls = 'ca ca--' + size + (o.cls ? ' ' + o.cls : '');
    var style = rot ? ' style="--rot:' + rot + 'deg;transform:rotate(' + rot + 'deg)"' : '';
    var dims = r ? ' width="' + r[0] + '" height="' + r[1] + '"' : '';
    var a11y = o.alt ? ' alt="' + esc(o.alt) + '"' : ' alt="" aria-hidden="true"';
    var load = o.eager ? '' : ' loading="lazy"';

    return '<img class="' + cls + '" src="' + DIRS[kind] + o.name + '.webp"' +
      dims + a11y + load + ' decoding="async"' + style + '>';
  }

  function crayon(name, o) { return asset(Object.assign({ kind: 'crayon', name: name }, o)); }
  function face(name, o)   { return asset(Object.assign({ kind: 'face',   name: name }, o)); }
  function doodle(name, o) { return asset(Object.assign({ kind: 'doodle', name: name }, o)); }

  /* A character head inside a rough hand-drawn circle. */
  function stampRing(expression, o) {
    o = o || {};
    var ring = o.ring || 'circle-red';
    return '<span class="stamp-ring' + (o.cls ? ' ' + o.cls : '') + '">' +
      '<img class="stamp-ring__ring" src="' + DIRS.doodle + ring + '.webp" alt="" aria-hidden="true" loading="lazy" decoding="async">' +
      '<img class="stamp ' + (o.size ? 'stamp--' + o.size : '') + '" src="' + DIRS.face + expression + '.webp"' +
      (o.alt ? ' alt="' + esc(o.alt) + '"' : ' alt="" aria-hidden="true"') +
      ' loading="lazy" decoding="async"' +
      (o.rot ? ' style="transform:rotate(' + o.rot + 'deg)"' : '') + '>' +
      '</span>';
  }

  /* A word with a crayon mark layered behind it. */
  function mark(text, o) {
    o = o || {};
    var kind = o.kind || 'under';          // under | circle | hi
    var art = o.art || 'underline-red';
    return '<span class="mark mark--' + kind + '">' + esc(text) +
      '<img src="' + DIRS.doodle + art + '.webp" alt="" aria-hidden="true" loading="lazy" decoding="async"></span>';
  }

  /* A handwritten note with an optional doodle beside it. */
  function note(text, o) {
    o = o || {};
    return '<p class="note' + (o.tone ? ' note--' + o.tone : '') + (o.cls ? ' ' + o.cls : '') + '">' +
      (o.art ? doodle(o.art, { size: o.artSize || 'sm', rot: o.artRot }) : '') +
      '<span class="note__text">' + esc(text) + '</span></p>';
  }

  /* ---------------------------------------------------------
     Declarative pass — turn data-* placeholders into images.
     --------------------------------------------------------- */

  function paint(root) {
    root = root || document;
    var nodes = root.querySelectorAll('[data-crayon], [data-face], [data-doodle]');
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var kind = el.hasAttribute('data-face') ? 'face'
        : el.hasAttribute('data-doodle') ? 'doodle' : 'crayon';
      var name = el.getAttribute('data-' + kind);
      el.innerHTML = asset({
        kind: kind,
        name: name,
        size: el.dataset.size,
        rot: el.dataset.rot,
        alt: el.dataset.alt,
        eager: el.hasAttribute('data-eager')
      });
      el.classList.add('ca-host');
      if (!el.dataset.alt) el.setAttribute('aria-hidden', 'true');
      if (el.dataset.rot) el.style.setProperty('--rot', el.dataset.rot + 'deg');
      el.removeAttribute('data-crayon');
      el.removeAttribute('data-face');
      el.removeAttribute('data-doodle');
    }
  }

  /* The turbulence filter that roughens the crayon headlines.
     Injected once, from JS, so no page has to carry the markup. */
  function mountFilter() {
    if (document.getElementById('crayonEdge')) return;
    var ns = 'http://www.w3.org/2000/svg';
    var svg = document.createElementNS(ns, 'svg');
    svg.setAttribute('width', '0');
    svg.setAttribute('height', '0');
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('focusable', 'false');
    svg.style.cssText = 'position:absolute;width:0;height:0;overflow:hidden';
    svg.innerHTML =
      /* the big poster words can take a lot of roughening */
      '<filter id="crayonEdge" x="-4%" y="-8%" width="108%" height="116%"' +
      ' color-interpolation-filters="sRGB" filterUnits="objectBoundingBox">' +
      '<feTurbulence type="fractalNoise" baseFrequency="0.019 0.036" numOctaves="4" seed="17" result="n"/>' +
      '<feDisplacementMap in="SourceGraphic" in2="n" scale="7" xChannelSelector="R" yChannelSelector="G"/>' +
      '</filter>' +
      /* section headings are much smaller, so they get a gentler hand */
      '<filter id="crayonEdgeSm" x="-4%" y="-10%" width="108%" height="120%"' +
      ' color-interpolation-filters="sRGB" filterUnits="objectBoundingBox">' +
      '<feTurbulence type="fractalNoise" baseFrequency="0.05 0.09" numOctaves="3" seed="9" result="n"/>' +
      '<feDisplacementMap in="SourceGraphic" in2="n" scale="2.2" xChannelSelector="R" yChannelSelector="G"/>' +
      '</filter>';
    document.body.appendChild(svg);
  }

  /* ---------------------------------------------------------
     Fit a poster word to its container.

     The CSS sizes a display word as 100cqw / --em, where --em is the
     width of the widest line in ems of the display face. We measure
     that once the font has loaded, so any headline fills its column
     exactly without anyone hand-tuning a font size.
     --------------------------------------------------------- */

  function fitWords(root) {
    var els = (root || document).querySelectorAll('.poster__word');
    if (!els.length) return;

    /* Measure the widest line as it is actually drawn — real font, real
       letter-spacing — and express it in ems. The CSS then sets the font
       size to 100cqw / --em, so the word fills its column exactly. */
    function measure(el) {
      var size = parseFloat(getComputedStyle(el).fontSize);
      if (!size) return;
      var lines = el.querySelectorAll('.ln');
      var list = lines.length ? Array.prototype.slice.call(lines) : [el];
      var range = document.createRange();
      var widest = 0;
      list.forEach(function (l) {
        if (!(l.textContent || '').trim()) return;
        range.selectNodeContents(l);
        var w = range.getBoundingClientRect().width;
        if (w > widest) widest = w;
      });
      range.detach && range.detach();
      if (!widest) return;
      // a little headroom for the turbulence filter, which pushes ink outward
      el.style.setProperty('--em', (widest / size * 1.02).toFixed(3));
    }

    function run() {
      Array.prototype.forEach.call(els, measure);
      // a second pass settles any line that changed which of them is widest
      Array.prototype.forEach.call(els, measure);
    }

    run();
    if (document.fonts && document.fonts.ready) document.fonts.ready.then(run);
    var t;
    addEventListener('resize', function () { clearTimeout(t); t = setTimeout(run, 150); });
  }

  global.Crayon = {
    asset: asset, crayon: crayon, face: face, doodle: doodle,
    stampRing: stampRing, mark: mark, note: note,
    paint: paint, mountFilter: mountFilter, fitWords: fitWords, esc: esc
  };

  /* short aliases for the render files */
  global.crayon = crayon;
  global.face = face;
  global.doodle = doodle;
  global.stampRing = stampRing;
  global.markWord = mark;
  global.handNote = note;
  global.paintCrayon = paint;
  global.fitWords = fitWords;
})(window);
